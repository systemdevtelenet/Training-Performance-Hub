-- One batch per distinct legacy cohort group. Original text fields remain in
-- legacy_training_source_rows, including dates that cannot be safely parsed.
with raw_groups as (
  select distinct
    r.program_code,
    r.source_batch,
    r.account_text,
    r.source_start_date,
    r.source_endorsed_date,
    r.source_month,
    r.source_quarter,
    'LEGACY-' || r.program_code || '-' ||
      md5(jsonb_build_array(r.source_batch, r.account_text, r.source_start_date,
                            r.source_endorsed_date, r.source_month, r.source_quarter)::text) as batch_code
  from _training_system_legacy_rows r
), parsed_groups as (
  select g.*,
    case
      when g.source_start_date ~ '^\d{4}-\d{2}-\d{2}$'
        and pg_input_is_valid(g.source_start_date, 'date')
        then g.source_start_date::date
      when g.source_start_date ~ '^\d{1,2}/\d{1,2}/\d{4}$'
        and pg_input_is_valid(
          split_part(g.source_start_date, '/', 3) || '-' ||
          lpad(split_part(g.source_start_date, '/', 1), 2, '0') || '-' ||
          lpad(split_part(g.source_start_date, '/', 2), 2, '0'), 'date')
        then make_date(split_part(g.source_start_date, '/', 3)::int,
                       split_part(g.source_start_date, '/', 1)::int,
                       split_part(g.source_start_date, '/', 2)::int)
      else null
    end as parsed_start_date,
    case
      when g.source_endorsed_date ~ '^\d{4}-\d{2}-\d{2}$'
        and pg_input_is_valid(g.source_endorsed_date, 'date')
        then g.source_endorsed_date::date
      when g.source_endorsed_date ~ '^\d{1,2}/\d{1,2}/\d{4}$'
        and pg_input_is_valid(
          split_part(g.source_endorsed_date, '/', 3) || '-' ||
          lpad(split_part(g.source_endorsed_date, '/', 1), 2, '0') || '-' ||
          lpad(split_part(g.source_endorsed_date, '/', 2), 2, '0'), 'date')
        then make_date(split_part(g.source_endorsed_date, '/', 3)::int,
                       split_part(g.source_endorsed_date, '/', 1)::int,
                       split_part(g.source_endorsed_date, '/', 2)::int)
      else null
    end as parsed_endorsed_date
  from raw_groups g
)
insert into training_system.training_batches
  (program_id, account_id, batch_code, wave, start_date, endorsed_date, status, quarter)
select p.program_id,
       a.account_id,
       g.batch_code,
       case when g.program_code = 'PST'
                  and g.source_batch ~ '^\d+$'
                  and g.source_batch::numeric between 1 and 2147483647
            then g.source_batch::integer else null end,
       g.parsed_start_date,
       g.parsed_endorsed_date,
       'IMPORTED',
       g.source_quarter
from parsed_groups g
join training_system.training_programs p on p.program_code = g.program_code
left join lateral (
  select ac.account_id
  from public.accounts ac
  where lower(btrim(ac.account_name)) = lower(btrim(g.account_text))
     or lower(btrim(ac.account_code)) = lower(btrim(g.account_text))
  order by case when lower(btrim(ac.account_name)) = lower(btrim(g.account_text)) then 0 else 1 end,
           ac.account_id
  limit 1
) a on true
on conflict (program_id, batch_code) do nothing;

