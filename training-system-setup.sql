-- The old PST day columns contain 40+ distinct values, including comments and
-- summary figures. Normalize only recognized attendance codes; the complete
-- original row remains in the source archive. Training-day number is retained
-- without pretending it is a calendar date.
insert into training_system.training_attendance
  (enrollment_id, training_day, attendance_code, notes)
select l.enrollment_id,
       day.day_number,
       case lower(btrim(s.row_data->>('att_status_day_' || day.day_number::text)))
         when 'p' then 'P'
         when 'a' then 'A'
         when 'late' then 'L'
         when 'l' then 'L'
         when 'u' then 'U'
         when 'ut' then 'U'
         when 'undertime' then 'U'
       end,
       'Copied from public.product_spec_training.att_status_day_' || day.day_number::text
from training_system.legacy_training_source_rows s
join training_system.legacy_training_source_links l
  on l.source_table = s.source_table and l.source_key = s.source_key
cross join lateral generate_series(1, 62) as day(day_number)
where s.source_table = 'public.product_spec_training'
  and lower(btrim(s.row_data->>('att_status_day_' || day.day_number::text)))
      in ('p', 'a', 'late', 'l', 'u', 'ut', 'undertime')
on conflict do nothing;

