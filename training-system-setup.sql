-- Copy every old raw row into a normalized enrollment, one source row per
-- person/enrollment because the legacy tables have no primary key. This avoids
-- merging same-name people without a reliable identity key.
with candidates as materialized (
  select r.source_table,
         r.source_key,
         person.person_id,
         batch.batch_id,
         coalesce(r.source_status, 'ACTIVE') as status,
         r.parsed_start_date as enrolled_on,
         r.parsed_endorsed_date as endorsed_on,
         trainer.id as trainer_employee_id
  from (
    select r.*,
      case
        when r.source_start_date ~ '^\d{4}-\d{2}-\d{2}$'
          and pg_input_is_valid(r.source_start_date, 'date')
          then r.source_start_date::date
        when r.source_start_date ~ '^\d{1,2}/\d{1,2}/\d{4}$'
          and pg_input_is_valid(split_part(r.source_start_date, '/', 3) || '-' ||
            lpad(split_part(r.source_start_date, '/', 1), 2, '0') || '-' ||
            lpad(split_part(r.source_start_date, '/', 2), 2, '0'), 'date')
          then make_date(split_part(r.source_start_date, '/', 3)::int,
                         split_part(r.source_start_date, '/', 1)::int,
                         split_part(r.source_start_date, '/', 2)::int)
        else null
      end as parsed_start_date,
      case
        when r.source_endorsed_date ~ '^\d{4}-\d{2}-\d{2}$'
          and pg_input_is_valid(r.source_endorsed_date, 'date')
          then r.source_endorsed_date::date
        when r.source_endorsed_date ~ '^\d{1,2}/\d{1,2}/\d{4}$'
          and pg_input_is_valid(split_part(r.source_endorsed_date, '/', 3) || '-' ||
            lpad(split_part(r.source_endorsed_date, '/', 1), 2, '0') || '-' ||
            lpad(split_part(r.source_endorsed_date, '/', 2), 2, '0'), 'date')
          then make_date(split_part(r.source_endorsed_date, '/', 3)::int,
                         split_part(r.source_endorsed_date, '/', 1)::int,
                         split_part(r.source_endorsed_date, '/', 2)::int)
        else null
      end as parsed_endorsed_date,
      'LEGACY-' || r.program_code || '-' ||
        md5(jsonb_build_array(r.source_batch, r.account_text, r.source_start_date,
                              r.source_endorsed_date, r.source_month, r.source_quarter)::text) as batch_code
    from _training_system_legacy_rows r
  ) r
  join training_system.people person
    on person.external_person_code = r.source_table || ':' || r.source_key
  join training_system.training_programs program on program.program_code = r.program_code
  join training_system.training_batches batch
    on batch.program_id = program.program_id and batch.batch_code = r.batch_code
  left join lateral (
    select min(e.id) as id
    from public.employees e
    where r.assigned_trainer is not null
      and lower(btrim(e.employee_name)) = lower(btrim(r.assigned_trainer))
    having count(*) = 1
  ) trainer on true
  where not exists (
    select 1 from training_system.legacy_training_source_links l
    where l.source_table = r.source_table and l.source_key = r.source_key
  )
), inserted as (
  insert into training_system.enrollments
    (person_id, batch_id, trainer_employee_id, status, enrolled_on, endorsed_on)
  select person_id, batch_id, trainer_employee_id, status, enrolled_on, endorsed_on
  from candidates
  returning enrollment_id, person_id, batch_id
)
insert into training_system.legacy_training_source_links
  (source_table, source_key, person_id, batch_id, enrollment_id)
select c.source_table, c.source_key, i.person_id, i.batch_id, i.enrollment_id
from inserted i
join candidates c on c.person_id = i.person_id and c.batch_id = i.batch_id
on conflict (source_table, source_key) do nothing;

-- Copy all rows from the existing normalized public trainees/batches model.
-- Names were not present in that source, so display_name remains an explicit
-- placeholder rather than inventing a real identity.
with candidates as materialized (
  select t.trainee_id,
         person.person_id,
         batch.batch_id as target_batch_id
  from public.trainees t
  join training_system.people person
    on person.external_person_code = 'public.trainees:person_id:' || t.person_id::text
  join training_system.training_programs program
    on program.program_code = 'LEGACY_NORMALIZED'
  left join training_system.training_batches batch
    on batch.program_id = program.program_id
   and batch.batch_code = case
     when t.batch_id is null then 'LEGACY-PUBLIC-UNASSIGNED'
     else 'LEGACY-PUBLIC-BATCH-' || t.batch_id::text
   end
  where not exists (
    select 1 from training_system.legacy_training_source_links l
    where l.source_table = 'public.trainees'
      and l.source_key = 'trainee_id:' || t.trainee_id::text
  )
), inserted as (
  insert into training_system.enrollments (person_id, batch_id, status)
  select c.person_id, c.target_batch_id, 'IMPORTED'
  from candidates c
  where c.target_batch_id is not null
  returning enrollment_id, person_id, batch_id
)
insert into training_system.legacy_training_source_links
  (source_table, source_key, person_id, batch_id, enrollment_id)
