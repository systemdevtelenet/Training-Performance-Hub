-- Training Performance Hub schema setup and legacy data copy.
-- Mirrors qa_system conventions: dedicated schema, exposed through the local
-- PostgREST schema list, RLS enabled, and service_role-only table privileges
-- until explicit authenticated policies are designed.
--
-- Safe to rerun. Copies source data without updating or deleting any public
-- rows. Shared reference tables (employees, accounts, auth.users) remain public.
--
-- To expose this schema on the local Supabase stack, include training_system in
-- PGRST_DB_SCHEMAS in the Supabase project's .env, then recreate the rest service.

begin;

-- 1. Create project-owned tables.
create schema if not exists training_system;

create table if not exists training_system.training_programs (
  program_id bigint generated by default as identity primary key,
  program_code text not null unique,
  program_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists training_system.training_batches (
  batch_id bigint generated by default as identity primary key,
  program_id bigint not null
    references training_system.training_programs(program_id) on delete restrict,
  account_id bigint
    references public.accounts(account_id) on delete restrict,
  batch_code text not null,
  wave integer,
  start_date date,
  endorsed_date date,
  status text not null default 'PLANNED',
  quarter text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint training_batches_program_batch_code_uk unique (program_id, batch_code),
  constraint training_batches_wave_positive_ck check (wave is null or wave > 0)
);

create table if not exists training_system.people (
  person_id bigint generated by default as identity primary key,
  external_person_code text,
  display_name text not null,
  email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists people_external_person_code_uk
  on training_system.people (lower(btrim(external_person_code)))
  where nullif(btrim(external_person_code), '') is not null;

create table if not exists training_system.enrollments (
  enrollment_id bigint generated by default as identity primary key,
  person_id bigint not null
    references training_system.people(person_id) on delete restrict,
  batch_id bigint not null
    references training_system.training_batches(batch_id) on delete restrict,
  trainer_employee_id bigint
    references public.employees(id) on delete set null,
  status text not null default 'ACTIVE',
  enrolled_on date,
  endorsed_on date,
  completed_on date,
  is_loss boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists enrollments_batch_status_idx
  on training_system.enrollments (batch_id, status);

create index if not exists enrollments_person_idx
  on training_system.enrollments (person_id);

create index if not exists enrollments_trainer_idx
  on training_system.enrollments (trainer_employee_id)
  where trainer_employee_id is not null;

create table if not exists training_system.training_attendance (
  attendance_id bigint generated by default as identity primary key,
  enrollment_id bigint not null
    references training_system.enrollments(enrollment_id) on delete restrict,
  attendance_date date not null,
  attendance_code text not null
    check (attendance_code in ('P', 'L', 'U', 'A')),
  notes text,
  recorded_by_employee_id bigint
    references public.employees(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint training_attendance_enrollment_date_uk
    unique (enrollment_id, attendance_date)
);

create index if not exists training_attendance_date_idx
  on training_system.training_attendance (attendance_date);

create table if not exists training_system.app_roles (
  app_role_id bigint generated by default as identity primary key,
  role_code text not null unique,
  role_name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists training_system.user_role_assignments (
  user_id uuid not null references auth.users(id) on delete restrict,
  app_role_id bigint not null
    references training_system.app_roles(app_role_id) on delete restrict,
  assigned_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (user_id, app_role_id)
);

create index if not exists user_role_assignments_app_role_idx
  on training_system.user_role_assignments (app_role_id);

create table if not exists training_system.activity_logs (
  activity_id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_employee_id bigint references public.employees(id) on delete set null,
  actor_label text,
  title text not null,
  description text not null,
  icon_type text not null,
  created_at timestamptz not null default now()
);

create index if not exists activity_logs_created_at_idx
  on training_system.activity_logs (created_at desc);

create index if not exists activity_logs_actor_employee_idx
