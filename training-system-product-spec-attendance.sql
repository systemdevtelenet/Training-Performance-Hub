-- Normalize product_spec_training's att_status_day_1..62 values.
-- The parent product_spec_training row already identifies the trainee and wave.
-- Training-day numbers are retained; attendance_date stays NULL until a real
-- calendar schedule is available. Existing wide columns are intentionally kept.

begin;

create table if not exists training_system.product_spec_training_attendance (
  attendance_id bigint generated by default as identity primary key,
  product_spec_training_id bigint not null
    references training_system.product_spec_training(id) on delete restrict,
  training_day smallint not null
    check (training_day > 0),
  attendance_date date,
  status text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_spec_training_attendance_parent_day_uk
    unique (product_spec_training_id, training_day)
);

create index if not exists product_spec_training_attendance_date_idx
  on training_system.product_spec_training_attendance (attendance_date)
  where attendance_date is not null;

alter table training_system.product_spec_training_attendance
  enable row level security;

grant all privileges on table training_system.product_spec_training_attendance
  to service_role;
grant usage, select on sequence
  training_system.product_spec_training_attendance_attendance_id_seq
  to service_role;

insert into training_system.product_spec_training_attendance
  (product_spec_training_id, training_day, status)
select p.id,
       substring(k.column_name from '^att_status_day_([0-9]+)$')::smallint,
       k.status
from training_system.product_spec_training p
cross join lateral jsonb_each_text(to_jsonb(p)) as k(column_name, status)
where k.column_name ~ '^att_status_day_[0-9]+$'
  and nullif(btrim(k.status), '') is not null
on conflict (product_spec_training_id, training_day) do nothing;

commit;

-- Drop the legacy wide attendance columns only after their populated values
-- have been copied and verified in the normalized table.
begin;
do $$
declare
  missing_count bigint;
  drop_columns text;
begin
  select count(*) into missing_count
  from training_system.product_spec_training p
  cross join lateral jsonb_each_text(to_jsonb(p)) as k(column_name, status)
  left join training_system.product_spec_training_attendance a
    on a.product_spec_training_id = p.id
   and a.training_day = substring(k.column_name from '^att_status_day_([0-9]+)$')::smallint
   and a.status = k.status
  where k.column_name ~ '^att_status_day_[0-9]+$'
    and nullif(btrim(k.status), '') is not null
    and a.attendance_id is null;

  if missing_count <> 0 then
    raise exception 'Refusing to drop legacy columns: % attendance values are missing', missing_count;
  end if;

  select string_agg(format('drop column %I', column_name), ', ' order by column_name)
    into drop_columns
  from information_schema.columns
  where table_schema = 'training_system'
    and table_name = 'product_spec_training'
    and column_name ~ '^att_status_day_[0-9]+$';

  if drop_columns is not null then
    execute format('alter table training_system.product_spec_training %s', drop_columns);
  end if;
end;
$$;
commit;

-- Backfill only Training Performance Hub activity notifications. The filter
-- mirrors lib/actions/logger.ts:isTrainingLog and deduplicates per-recipient
-- copies of the same event.
begin;
alter table training_system.activity_logs
  add column if not exists title text,
  add column if not exists description text,
  add column if not exists icon_type text,
  add column if not exists author text,
  add column if not exists action_url text,
  add column if not exists source_notification_id bigint;

create unique index if not exists activity_logs_source_notification_id_uk
  on training_system.activity_logs (source_notification_id)
  where source_notification_id is not null;

insert into training_system.activity_logs
  (title, description, icon_type, author, action_url, source_notification_id, created_at)
with classified as (
  select n.*,
         lower(coalesce(n.title, '')) as title_lc,
         lower(coalesce(n.description, '')) as description_lc,
         lower(coalesce(n.action_url, '')) as url_lc
  from training_system.notifications n
), eligible as (
  select *
  from classified
  where not (
    title_lc like '%evaluation%' or title_lc like '%calibration%'
    or title_lc like '%qa %' or title_lc like 'qa%'
    or description_lc like '%evaluation for%'
    or description_lc like '%submitted by qa%'
    or description_lc like '%removed by qas%'
    or description_lc like '%added by qas%'
    or description_lc like '%qas ray%'
    or description_lc like '%qa stephen%'
    or description_lc like '%qa josefura%'
    or description_lc like '%qa janine%'
    or description_lc like '%qa jordan%'
    or url_lc like '%/evaluation/%'
    or url_lc like '%guideline=%'
    or url_lc like '/accounts/%'
  )
  and (
    url_lc like '/traffic-lights%' or url_lc like '/trainees%'
    or url_lc like '/trainers%' or url_lc like '/history%'
    or url_lc like '/settings%' or url_lc like '/analytics%'
    or url_lc = '/'
    or title_lc like '%traffic light%' or title_lc like '%login%'
    or title_lc like '%trainee%' or title_lc like '%trainer%'
    or title_lc like '%offboard%' or title_lc like '%approval%'
    or title_lc like '%remark%' or title_lc like '%note%'
    or title_lc like '%reason%' or title_lc like '%attendance%'
    or title_lc like '%reliability%' or title_lc like '%export%'
    or title_lc like '%hub%' or title_lc like '%training%'
    or title_lc like '%employee profile%'
    or description_lc like '%attendance%'
    or description_lc like '%note%' or description_lc like '%reason%'
  )
), distinct_events as (
  select distinct on (title, description, created_at, action_url) *
  from eligible
  order by title, description, created_at, action_url, notification_id
)
select e.title,
       e.description,
       case
         when e.title_lc like '%login%' or e.title_lc like '%auth%'
           or e.description_lc like '%logged into%' then 'login'
         when e.title_lc like '%traffic%' then 'traffic'
         when e.title_lc like '%attendance%' or e.title_lc like '%leave%'
           or e.description_lc like '%attendance%' then 'attendance'
         when e.title_lc like '%note%' or e.title_lc like '%remark%'
           or e.description_lc like '%note%' then 'remark'
         when e.title_lc like '%employee%' or e.title_lc like '%trainer%'
           or e.title_lc like '%trainee%' then 'user'
         when e.title_lc like '%delete%' or e.title_lc like '%removed%'
           or e.description_lc like '%loss%' then 'alert'
         else 'activity'
       end,
       coalesce(nullif(btrim(split_part(split_part(e.description, '(by ', 2), ')', 1)), ''), 'System'),
       e.action_url,
       e.notification_id,
       e.created_at
from distinct_events e
on conflict (source_notification_id) where source_notification_id is not null
  do nothing;
commit;


-- Allow signed-in users to receive only their own notification events via Realtime.
begin;
grant usage on schema training_system to authenticated, service_role;
grant select on training_system.notifications to authenticated;
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'training_system'
      and tablename = 'notifications'
      and policyname = 'notifications_select_own'
  ) then
    create policy notifications_select_own
      on training_system.notifications
      for select to authenticated
      using (recipient_employee_id = (
        select e.id from public.employees e
        where lower(e.employee_email) = lower(auth.jwt() ->> 'email')
        order by e.id limit 1
      ));
  end if;
end;
$$;
do $$
declare relation_name text;
begin
  foreach relation_name in array array['notifications'] loop
    if not exists (
      select 1 from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'training_system'
        and tablename = relation_name
    ) then
      execute format('alter publication supabase_realtime add table training_system.%I', relation_name);
    end if;
  end loop;
end;
$$;
commit;
